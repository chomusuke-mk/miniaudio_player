    chk_opt!("ext.isrc", x.isrc, ex.isrc);
    chk_opt!("ext.barcode", x.barcode, ex.barcode);
    chk_opt!("ext.catalog_number", x.catalog_number, ex.catalog_number);
    chk_opt!("ext.arranger", x.arranger, ex.arranger);
    chk_opt!("ext.conductor", x.conductor, ex.conductor);
    chk_opt!("ext.director", x.director, ex.director);
    chk_opt!("ext.engineer", x.engineer, ex.engineer);
    chk_opt!("ext.lyricist", x.lyricist, ex.lyricist);
    chk_opt!("ext.mix_dj", x.mix_dj, ex.mix_dj);
