fn percent_encode(seg: &str) -> String {
    let mut out = String::with_capacity(seg.len());
    for &b in seg.as_bytes() {
        if b.is_ascii_alphanumeric() || matches!(b, b'_' | b'-' | b'.') {
            out.push(b as char);
        } else {
            out.push_str(&format!("%{:02X}", b));
        }
    }
    out
}

fn decode_url_path(raw: &str) -> String {
    let stripped = raw.split('?').next().unwrap_or(raw).trim_start_matches('/');
    let bytes = stripped.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%' && i + 2 < bytes.len() {
            if let Ok(hex_str) = std::str::from_utf8(&bytes[i + 1..i + 3]) {
                if let Ok(val) = u8::from_str_radix(hex_str, 16) {
                    out.push(val);
                    i += 3;
                    continue;
                }
            }
        }
        out.push(bytes[i]);
        i += 1;
    }
    String::from_utf8_lossy(&out).into_owned()
}

struct MetadataHttpServer {
    port: u16,
    stop: Arc<AtomicBool>,
    thread: Option<JoinHandle<()>>,
}

impl MetadataHttpServer {
    fn start(fixtures_dir: PathBuf) -> Self {
        let mut map: HashMap<String, Arc<[u8]>> = HashMap::new();
        for exp in EXPECTATIONS_27 {
            let full = fixtures_dir.join(exp.rel_path);
            let data = std::fs::read(&full)
                .unwrap_or_else(|e| panic!("Failed to read {:?}: {}", full, e));
            map.insert(exp.rel_path.to_string(), Arc::from(data));
        }
        let files = Arc::new(map);
        let listener = TcpListener::bind("127.0.0.1:0").expect("bind http test server");
        listener.set_nonblocking(true).expect("set nonblocking");
        let port = listener.local_addr().unwrap().port();
        let stop = Arc::new(AtomicBool::new(false));
        let stop_c = stop.clone();

        let thread = thread::spawn(move || {
            let mut workers: Vec<JoinHandle<()>> = Vec::new();
            while !stop_c.load(Ordering::Acquire) {
                match listener.accept() {
                    Ok((stream, _)) => {
                        let _ = stream.set_nonblocking(false);
                        let f = files.clone();
                        workers.retain(|w| !w.is_finished());
                        workers.push(thread::spawn(move || Self::handle_client(stream, f)));
                    }
                    Err(e) if e.kind() == std::io::ErrorKind::WouldBlock => {
                        thread::sleep(Duration::from_millis(2));
                    }
                    Err(_) => break,
                }
            }
            for w in workers {
                let _ = w.join();
            }
        });

        Self {
            port,
            stop,
            thread: Some(thread),
        }
    }

    fn url_for(&self, rel: &str) -> String {
        format!("http://127.0.0.1:{}/{}", self.port, percent_encode(rel))
    }

    fn handle_client(mut stream: TcpStream, files: Arc<HashMap<String, Arc<[u8]>>>) {
        let Ok(cloned) = stream.try_clone() else { return };
        let mut br = BufReader::new(cloned);
        let mut req_line = String::new();
        if br.read_line(&mut req_line).is_err() || req_line.is_empty() {
            return;
        }
        let mut parts = req_line.split_whitespace();
        let method = parts.next().unwrap_or("GET").to_ascii_uppercase();
        let raw_path = parts.next().unwrap_or("/");
        let rel_path = decode_url_path(raw_path);

        let mut range_hdr: Option<String> = None;
        loop {
            let mut h = String::new();
            if br.read_line(&mut h).is_err() || h.trim().is_empty() {
                break;
            }
            let low = h.to_ascii_lowercase();
            if let Some(rest) = low.strip_prefix("range:") {
                range_hdr = Some(rest.trim().to_string());
            }
        }

        let Some(data) = files.get(&rel_path) else {
            let _ = stream.write_all(b"HTTP/1.1 404 Not Found\r\nContent-Length: 0\r\n\r\n");
            return;
        };

        if method == "HEAD" {
            let hdr = format!(
                "HTTP/1.1 200 OK\r\nAccept-Ranges: bytes\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",
                data.len()
            );
            let _ = stream.write_all(hdr.as_bytes());
            return;
        }

        if let Some(r) = range_hdr.and_then(|s| s.strip_prefix("bytes=").map(str::to_string)) {
            let (a, b) = r.split_once('-').unwrap_or(("0", ""));
            let start: usize = a.parse().unwrap_or(0);
            let end: usize = if b.is_empty() {
                data.len().saturating_sub(1)
            } else {
                b.parse()
                    .unwrap_or(data.len().saturating_sub(1))
                    .min(data.len().saturating_sub(1))
            };
            if start <= end && start < data.len() {
                let slice = &data[start..=end];
                let hdr = format!(
                    "HTTP/1.1 206 Partial Content\r\nAccept-Ranges: bytes\r\nContent-Length: {}\r\nContent-Range: bytes {}-{}/{}\r\nConnection: close\r\n\r\n",
                    slice.len(),
                    start,
                    end,
                    data.len()
                );
                let _ = stream.write_all(hdr.as_bytes());
                let _ = stream.write_all(slice);
                return;
            }
        }

        let hdr = format!(
            "HTTP/1.1 200 OK\r\nAccept-Ranges: bytes\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",
            data.len()
        );
        let _ = stream.write_all(hdr.as_bytes());
        let _ = stream.write_all(data);
    }
}

impl Drop for MetadataHttpServer {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::Release);
        if let Some(jh) = self.thread.take() {
            let _ = jh.join();
        }
    }
}

