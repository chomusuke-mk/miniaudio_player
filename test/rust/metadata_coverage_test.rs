    chk_eq!("disc_number", meta.disc_number, exp.disc_number);
    chk_eq!("disc_total", meta.disc_total, exp.disc_total);
    chk_eq!("lyrics", meta.lyrics.as_deref(), exp.lyrics);
    chk_eq!("comment", meta.comment.as_deref(), exp.comment);
    match (meta.bpm, exp.bpm) {
        (Some(a), Some(b)) if (a - b).abs() < 0.05 => {}
        (None, None) => {}
        _ => errs.push(format!("bpm: got {:?} != expected {:?}", meta.bpm, exp.bpm)),
    }
    chk_eq!("replay_gain_track_gain", meta.replay_gain_track_gain.as_deref(), exp.rg_tg);
    chk_eq!("replay_gain_track_peak", meta.replay_gain_track_peak.as_deref(), exp.rg_tp);
    chk_eq!("replay_gain_album_gain", meta.replay_gain_album_gain.as_deref(), exp.rg_ag);
    chk_eq!("replay_gain_album_peak", meta.replay_gain_album_peak.as_deref(), exp.rg_ap);

    // Pictures verification (exact count + per-picture verification regardless of ordering)
    if meta.pictures.len() != exp.pictures.len() {
        errs.push(format!(
            "pictures.len()={} != expected {} (actual={:?})",
            meta.pictures.len(),
            exp.pictures.len(),
            meta.pictures
                .iter()
                .map(|p| format!("{:?}/{:?}/{}B/{:?}", p.picture_type, p.mime_type, p.bytes.len(), p.description))
                .collect::<Vec<_>>()
        ));
    } else {
        for (idx, ep) in exp.pictures.iter().enumerate() {
            let matched = meta.pictures.iter().any(|ap| {
                ap.mime_type == Some(ep.mime)
                    && ap.bytes.len() == ep.byte_len
                    && ap.picture_type == ep.pic_type
                    && verify_image_magic(ep.mime, &ap.bytes)
                    && (ep.desc.is_none() || ap.description.as_deref() == ep.desc)
            });
            if !matched {
                errs.push(format!(
                    "picture[{}] missing match for ({:?}, {:?}, desc={:?}, {}B); actual={:?}",
                    idx,
                    ep.pic_type,
                    ep.mime,
                    ep.desc,
                    ep.byte_len,
                    meta.pictures
                        .iter()
                        .map(|p| format!("{:?}/{:?}/{}B/{:?}", p.picture_type, p.mime_type, p.bytes.len(), p.description))
                        .collect::<Vec<_>>()
                ));
            }
        }
    }

    // Chapters verification
    if meta.chapters.len() != exp.chapters.len() {
        errs.push(format!(
            "chapters.len()={} != expected {} (actual={:?})",
            meta.chapters.len(),
            exp.chapters.len(),
            meta.chapters
        ));
    } else {
        for (i, (etitle, estart)) in exp.chapters.iter().enumerate() {
            let ac = &meta.chapters[i];
            if ac.title != *etitle {
                errs.push(format!("chapter[{}].title={:?} != {:?}", i, ac.title, etitle));
            }
            if ac.start_ms.abs_diff(*estart) > 5 {
                errs.push(format!("chapter[{}].start_ms={} != ~{}", i, ac.start_ms, estart));
            }
            if ac.end_ms < ac.start_ms {
                errs.push(format!("chapter[{}].end_ms={} < start_ms={}", i, ac.end_ms, ac.start_ms));
            }
        }
    }

    // Extended 62 fields
    let x = &meta.extended;
    let ex = &exp.extended;
    chk_opt!("ext.music_brainz_recording_id", x.music_brainz_recording_id, ex.music_brainz_recording_id);
    chk_opt!("ext.music_brainz_track_id", x.music_brainz_track_id, ex.music_brainz_track_id);
    chk_opt!("ext.music_brainz_release_id", x.music_brainz_release_id, ex.music_brainz_release_id);
    chk_opt!("ext.music_brainz_release_group_id", x.music_brainz_release_group_id, ex.music_brainz_release_group_id);
    chk_opt!("ext.music_brainz_artist_id", x.music_brainz_artist_id, ex.music_brainz_artist_id);
    chk_opt!("ext.music_brainz_release_artist_id", x.music_brainz_release_artist_id, ex.music_brainz_release_artist_id);
    chk_opt!("ext.music_brainz_work_id", x.music_brainz_work_id, ex.music_brainz_work_id);
    chk_opt!("ext.music_brainz_release_type", x.music_brainz_release_type, ex.music_brainz_release_type);
    chk_opt!("ext.acoust_id", x.acoust_id, ex.acoust_id);
