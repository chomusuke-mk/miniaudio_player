                      child: DropdownButton<AudioTrack>(
                        value: _selectedTrack,
                        isExpanded: true,
                        items: _availableTracks.map((track) {
                          final isFallback = track.isGenerated;
                          return DropdownMenuItem<AudioTrack>(
                            value: track,
                            child: Row(
                              children: [
                                Icon(
                                  isFallback
                                      ? Icons.graphic_eq
                                      : Icons.audiotrack,
                                  size: 18,
