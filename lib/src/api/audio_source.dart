import 'dart:typed_data';

import '../loader/custom_byte_provider.dart';
import '../rust/api/types.dart' as rust_types;

/// Callback signature for supplying additional items when Infinite Mix reaches
/// the end of the active queue in LoopMode.off.
typedef InfiniteMixProvider<T> = Future<List<AudioSource<T>>> Function(
  int count,
);

/// Represents a source of audio playable by [MiniaudioPlayer] or [MiniaudioEngine].
///
/// Designed with zero redundancy:
/// - [AudioSource.new]: Unified constructor accepting either a [String] (local file path,
///   remote HTTP/HTTPS URL, HLS m3u8 stream) or raw audio bytes ([Uint8List] / `List<int>`).
/// - [AudioSource.custom]: Constructor for custom byte streams in Dart (DRM, encrypted
///   decryption, tokenized storage) via [CustomByteProvider].
sealed class AudioSource<T> {
  int? _id;

  /// Internal monotonically increasing queue entry identifier assigned internally by
  /// [MiniaudioEngine] to distinguish duplicate tracks within the same queue.
  int? get id => _id;

  /// Optional caller-owned domain object (e.g. metadata or model reference).
  /// Preserved by reference without cloning.
  final T? data;

  /// Optional ReplayGain track loudness gain in decibels (e.g. `-6.5`).
  final double? replayGainDb;

  /// Optional ReplayGain linear peak amplitude (`1.0` = `0 dBFS`).
  final double? replayPeak;

  AudioSource._({
    this.data,
    this.replayGainDb,
    this.replayPeak,
    int? internalId,
  }) : _id = internalId;

  /// Internal helper to attach an identifier generated by the engine.
  void attachEngineId(int newId) {
    _id ??= newId;
  }

  /// Creates an audio source from a [String] (local path, URL, HLS stream)
  /// or in-memory audio bytes ([Uint8List] / `List<int>`).
  ///
  /// Optional [headers] are passed to the HTTP/HLS request when [source] is a remote URL.
  /// Optional [data] attaches a domain object, while [replayGainDb] and [replayPeak]
  /// provide track-level loudness normalization metadata.
  factory AudioSource(
    Object source, {
    Map<String, String>? headers,
    T? data,
    double? replayGainDb,
    double? replayPeak,
  }) {
    if (source is AudioSource) {
      if (source is AudioSource<T> &&
          headers == null &&
          data == null &&
          replayGainDb == null &&
          replayPeak == null) {
        return source;
      }
      final effectiveData = data ?? (source.data is T ? source.data as T : null);
      final effectiveReplayGainDb = replayGainDb ?? source.replayGainDb;
      final effectiveReplayPeak = replayPeak ?? source.replayPeak;
      final effectiveId = source.id;

      if (source is UriAudioSource) {
        return UriAudioSource<T>(
          source.sourceString,
          headers: headers ?? source.headers,
          data: effectiveData,
          replayGainDb: effectiveReplayGainDb,
          replayPeak: effectiveReplayPeak,
          internalId: effectiveId,
        );
      }
      if (source is MemoryAudioSource) {
        return MemoryAudioSource<T>(
          source.bytes,
          data: effectiveData,
          replayGainDb: effectiveReplayGainDb,
          replayPeak: effectiveReplayPeak,
          internalId: effectiveId,
        );
      }
      if (source is CustomAudioSource) {
        return CustomAudioSource<T>(
          source.provider,
          data: effectiveData,
          replayGainDb: effectiveReplayGainDb,
          replayPeak: effectiveReplayPeak,
          internalId: effectiveId,
        );
      }
    }
    if (source is Uri) {
      if (source.data != null) {
        return MemoryAudioSource<T>(
          source.data!.contentAsBytes(),
          data: data,
          replayGainDb: replayGainDb,
          replayPeak: replayPeak,
        );
      }
      return UriAudioSource<T>(
        source.toString(),
        headers: headers,
        data: data,
        replayGainDb: replayGainDb,
        replayPeak: replayPeak,
      );
    }
    if (source is String) {
      final str = source.trim();
      if (str.toLowerCase().startsWith('data:')) {
        try {
          final uriData = UriData.parse(str);
          return MemoryAudioSource<T>(
            uriData.contentAsBytes(),
            data: data,
            replayGainDb: replayGainDb,
            replayPeak: replayPeak,
          );
        } catch (_) {
          return UriAudioSource<T>(
            str,
            headers: headers,
            data: data,
            replayGainDb: replayGainDb,
            replayPeak: replayPeak,
          );
        }
      }
      return UriAudioSource<T>(
        str,
        headers: headers,
        data: data,
        replayGainDb: replayGainDb,
        replayPeak: replayPeak,
      );
    }
    if (source is Uint8List) {
      return MemoryAudioSource<T>(
        source,
        data: data,
        replayGainDb: replayGainDb,
        replayPeak: replayPeak,
      );
    }
    if (source is List<int>) {
      return MemoryAudioSource<T>(
        Uint8List.fromList(source),
        data: data,
        replayGainDb: replayGainDb,
        replayPeak: replayPeak,
      );
    }
    throw ArgumentError.value(
      source,
      'source',
      'AudioSource requires a String (path or URL) or Uint8List (audio bytes), got ${source.runtimeType}',
    );
  }

  /// Creates a custom audio source driven by a user-supplied [CustomByteProvider]
  /// for custom DRM or encrypted byte decryption.
  factory AudioSource.custom(
    CustomByteProvider provider, {
    T? data,
    double? replayGainDb,
    double? replayPeak,
  }) = CustomAudioSource<T>;

  /// Canonical key identifying the underlying audio resource.
  String get sourceKey;

  /// Whether this item has non-empty source coordinates that can be opened.
  bool get hasValidSource;

  /// Converts this source to Rust's internal queue representation.
  rust_types.RustAudioSource toRustSource([int? autoId]);

  /// Creates a copy of this [AudioSource] with updated fields while preserving
  /// the internal identifier and data unless overridden.
  AudioSource<T> copyWith({
    T? data,
    double? replayGainDb,
    double? replayPeak,
  });

  /// Returns a copy of this [AudioSource] associated with a new generic data payload [data]
  /// and specialized to the new generic type parameter [R].
  AudioSource<R> withData<R>(R? data) => AudioSource<R>(
        this,
        data: data,
      );

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is AudioSource &&
          runtimeType == other.runtimeType &&
          _id == other._id &&
          sourceKey == other.sourceKey &&
          data == other.data &&
          replayGainDb == other.replayGainDb &&
          replayPeak == other.replayPeak;

  @override
  int get hashCode => Object.hash(
        _id,
        sourceKey,
        data,
        replayGainDb,
        replayPeak,
      );
}

/// An audio source represented by a string path or URL handled natively in Rust.
final class UriAudioSource<T> extends AudioSource<T> {
  /// The local file path or remote URL.
  final String sourceString;

  /// Optional HTTP headers for network/HLS sources.
  final Map<String, String>? headers;

  UriAudioSource(
    this.sourceString, {
    this.headers,
    super.data,
    super.replayGainDb,
    super.replayPeak,
    super.internalId,
  }) : super._();

  @override
  String get sourceKey => 'uri:$sourceString';

  @override
  bool get hasValidSource => sourceString.trim().isNotEmpty;

  @override
  rust_types.RustAudioSource toRustSource([int? autoId]) {
    final effectiveId = id ?? autoId ?? 0;
    return rust_types.RustAudioSource(
      id: effectiveId,
      source: sourceString,
      headers: headers?.entries
          .map((e) => rust_types.RustHttpHeader(key: e.key, value: e.value))
          .toList(),
      replayGainDb: replayGainDb,
      replayPeak: replayPeak,
    );
  }

  @override
  AudioSource<T> copyWith({
    T? data,
    double? replayGainDb,
    double? replayPeak,
    Map<String, String>? headers,
    String? sourceString,
  }) {
    final res = UriAudioSource<T>(
      sourceString ?? this.sourceString,
      headers: headers ?? this.headers,
      data: data ?? this.data,
      replayGainDb: replayGainDb ?? this.replayGainDb,
      replayPeak: replayPeak ?? this.replayPeak,
      internalId: _id,
    );
    return res;
  }

  @override
  String toString() => 'AudioSource($sourceString)';
}

/// An in-memory audio source backed by raw bytes in RAM.
final class MemoryAudioSource<T> extends AudioSource<T> {
  /// Raw audio file bytes.
  final Uint8List bytes;

  MemoryAudioSource(
    this.bytes, {
    super.data,
    super.replayGainDb,
    super.replayPeak,
    super.internalId,
  }) : super._();

  @override
  String get sourceKey => 'mem:${identityHashCode(bytes)}';

  @override
  bool get hasValidSource => bytes.isNotEmpty;

  @override
  rust_types.RustAudioSource toRustSource([int? autoId]) {
    final effectiveId = id ?? autoId ?? 0;
    return rust_types.RustAudioSource(
      id: effectiveId,
      source: '',
      dataBytes: bytes,
      replayGainDb: replayGainDb,
      replayPeak: replayPeak,
    );
  }

  @override
  AudioSource<T> copyWith({
    T? data,
    double? replayGainDb,
    double? replayPeak,
    Uint8List? bytes,
  }) {
    final res = MemoryAudioSource<T>(
      bytes ?? this.bytes,
      data: data ?? this.data,
      replayGainDb: replayGainDb ?? this.replayGainDb,
      replayPeak: replayPeak ?? this.replayPeak,
      internalId: _id,
    );
    return res;
  }

  @override
  String toString() => 'AudioSource(${bytes.lengthInBytes} bytes)';
}

/// A custom audio source backed by a Dart [CustomByteProvider] (e.g. for DRM decryption).
final class CustomAudioSource<T> extends AudioSource<T> {
  /// The underlying custom byte provider.
  final CustomByteProvider provider;

  CustomAudioSource(
    this.provider, {
    super.data,
    super.replayGainDb,
    super.replayPeak,
    super.internalId,
  }) : super._();

  @override
  String get sourceKey => 'custom:${provider.streamId}';

  @override
  bool get hasValidSource => true;

  @override
  rust_types.RustAudioSource toRustSource([int? autoId]) {
    final effectiveId = id ?? autoId ?? 0;
    return rust_types.RustAudioSource(
      id: effectiveId,
      source: 'custom://${provider.streamId}',
      replayGainDb: replayGainDb,
      replayPeak: replayPeak,
    );
  }

  @override
  AudioSource<T> copyWith({
    T? data,
    double? replayGainDb,
    double? replayPeak,
    CustomByteProvider? provider,
  }) {
    final res = CustomAudioSource<T>(
      provider ?? this.provider,
      data: data ?? this.data,
      replayGainDb: replayGainDb ?? this.replayGainDb,
      replayPeak: replayPeak ?? this.replayPeak,
      internalId: _id,
    );
    return res;
  }

  @override
  String toString() => 'AudioSource.custom(streamId: ${provider.streamId})';
}
